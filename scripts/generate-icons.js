// Render the shared CSS mark with the existing browser, without new dependencies.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { chromium } from "@playwright/test";
import { brandStyles, BRAND_COLORS } from "./brand-styles.js";
import { THEMES, DEFAULT_THEME } from "../lib/themes.js";

if (process.platform !== "darwin") {
  throw new Error("アイコン生成はGeorgiaを使用できるmacOSで実行してください");
}
const root = new URL("../", import.meta.url);
const directory = new URL("public/icons/", root);
const theme = await readFile(new URL("lib/theme.css", root), "utf8");
const appIcons = new URL("native/safari/Shared (App)/Assets.xcassets/AppIcon.appiconset/", root);
const catalog = JSON.parse(await readFile(new URL("Contents.json", appIcons), "utf8"));
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ channel: "chromium", headless: true });
const cache = new Map();
async function render(size, opaque = false, palette = BRAND_COLORS) {
  const key = `${size}/${opaque}/${palette.background}/${palette.foreground}`;
  if (cache.has(key)) return cache.get(key);
  // Fresh viewports avoid stale compositor tiles after resizing tiny pages.
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  try {
    await page.setContent('<span class="brand-mark" aria-hidden="true">10</span>');
    await page.addStyleTag({ content: `${theme}\n${await brandStyles(palette, { ios: opaque })}\n
      * { box-sizing: border-box; }
      html, body { margin: 0; background: ${opaque ? palette.background : "transparent"}; }
      .brand-mark { position: absolute; transform-origin: top left; }
    ` });
    await page.evaluate(() => document.fonts.ready);
    await page.locator(".brand-mark").evaluate((element, { size, opaque }) => {
      const scale = size * (opaque ? 1 : 0.875) / 32;
      element.style.width = `${30 * scale}px`;
      element.style.height = `${32 * scale}px`;
      element.style.left = `${(size - 30 * scale) / 2}px`;
      element.style.top = `${(size - 32 * scale) / 2}px`;
    }, { size, opaque });
    await page.locator(".brand-mark").evaluate(async element => {
      const image = new Image();
      image.src = getComputedStyle(element).backgroundImage.slice(5, -2);
      await image.decode();
    });
    const png = await page.screenshot({ omitBackground: !opaque });
    if (png.readUInt32BE(16) !== size || png.readUInt32BE(20) !== size || (opaque && png[25] !== 2)) {
      throw new Error(`PNGのサイズまたは不透明形式が正しくありません: ${key}`);
    }
    cache.set(key, png);
    return png;
  } finally { await page.close(); }
}
try {
  for (const size of [16, 32, 48, 128]) await writeFile(new URL(`${size}.png`, directory), await render(size));
  const written = new Set();
  for (const entry of catalog.images) {
    if (!entry.filename || written.has(entry.filename)) continue;
    const size = Number(entry.size.split("x")[0]) * Number((entry.scale ?? "1x").replace("x", ""));
    await writeFile(new URL(entry.filename, appIcons), await render(size, entry.platform === "ios"));
    written.add(entry.filename);
  }
  for (const path of ["native/safari/Shared (App)/Resources/Icon.png", "native/safari/Shared (App)/Assets.xcassets/LargeIcon.imageset/128.png"]) {
    await writeFile(new URL(path, root), await render(128));
  }
  const choices = [];
  const palettePage = await browser.newPage();
  await palettePage.setContent("<html><body></body></html>");
  await palettePage.addStyleTag({ content: theme });
  for (const entry of THEMES) {
    const palette = entry.id === DEFAULT_THEME ? BRAND_COLORS : await palettePage.evaluate(id => {
      document.documentElement.dataset.theme = id;
      const style = getComputedStyle(document.documentElement);
      const color = name => style.getPropertyValue(`--${name}`).trim();
      return color("scheme") === "dark" ? { background: color("paper"), foreground: color("accent") } : { background: color("accent"), foreground: color("paper") };
    }, entry.id);
    const id = entry.id === DEFAULT_THEME ? "AppIcon" : `AppIcon-${entry.id}`;
    if (entry.id !== DEFAULT_THEME) {
      const directory = new URL(`../${id}.appiconset/`, appIcons);
      await mkdir(directory, { recursive: true });
      await writeFile(new URL("icon.png", directory), await render(1024, true, palette));
      const images = [{ size: "1024x1024", idiom: "universal", platform: "ios", filename: "icon.png" }];
      await writeFile(new URL("Contents.json", directory), JSON.stringify({ images, info: { version: 1, author: "xcode" } }, null, 2) + "\n");
    }
    choices.push({ id, theme: entry.id, name: entry.name, reading: entry.reading, image: `data:image/png;base64,${(await render(128, true, palette)).toString("base64")}` });
  }
  await palettePage.close();
  await writeFile(new URL("native/safari/Shared (App)/Resources/AppIcons.js", root), `// Generated by npm run icons from the shared themes and brand artwork.\nglobalThis.APP_ICONS = ${JSON.stringify(choices, null, 2)};\n`);
} finally { await browser.close(); }
